/* Bind-test rather than parsing `ss`: a port we can bind is a port nothing
 * holds, which is exactly the question, and it needs no external tool. */
static bool mtx_port_is_bound(uint16_t port, int socktype)
{
    int fd = socket(AF_INET, socktype, 0);
    if (fd < 0) return false;
    struct sockaddr_in addr = {0};
    addr.sin_family = AF_INET;
    addr.sin_port = htons(port);
    addr.sin_addr.s_addr = htonl(INADDR_LOOPBACK);
    /* Deliberately no SO_REUSEADDR: we want "is anyone holding this". */
    bool in_use = (bind(fd, (struct sockaddr *)&addr, sizeof(addr)) != 0) && (errno == EADDRINUSE);
    close(fd);
    return in_use;
}

static int mtx_expect(bool ok, const char *what)
{
    if (!ok) {
        fprintf(stderr, "ASSERTION FAILED: %s\n", what);
        return 1;
    }
    printf("  ok: %s\n", what);
    return 0;
}

int gui_mediamtx_test_main(int seconds)
{
    if (seconds <= 0) seconds = 2;
    gui_mediamtx_config_t cfg = gui_mediamtx_default_config();

    if (!gui_mediamtx_probe()) {
        fprintf(stderr, "mediamtx not found on this host; nothing to test\n");
        return 2;
    }
    printf("mediamtx: %s (%s)\n", gui_mediamtx_binary_path(), gui_mediamtx_version());

    /* capture-node's ports, sampled before we touch anything. The assertion is
     * that starting our server changes none of them. */
    const uint16_t cn_tcp[] = { 8554, 18554, 28554 };
    bool cn_before[3];
    for (int i = 0; i < 3; i++) cn_before[i] = mtx_port_is_bound(cn_tcp[i], SOCK_STREAM);

    for (int i = 0; i < 3; i++) {
        if (mtx_port_is_bound(cfg.rtsp, SOCK_STREAM)) {
            fprintf(stderr, "port %u is already bound before we start\n", cfg.rtsp);
            return 1;
        }
        break;
    }

    char err[256];
    if (gui_mediamtx_start(&cfg, err, sizeof(err)) != 0) {
        fprintf(stderr, "start failed: %s\n", err);
        return 1;
    }
    printf("started pid %d, config %s\n",
           gui_mediamtx_get_status().child_pid, gui_mediamtx_get_status().config_path);

    /* Give every listener time to come up before asserting on them. */
    mtx_sleep(1.0);

    int bad = 0;
    bad |= mtx_expect(mtx_port_is_bound(cfg.rtsp, SOCK_STREAM), "rtsp port bound");
    bad |= mtx_expect(mtx_port_is_bound(cfg.hls, SOCK_STREAM), "hls port bound");
    bad |= mtx_expect(mtx_port_is_bound(cfg.webrtc_http, SOCK_STREAM), "webrtc http port bound");
    bad |= mtx_expect(mtx_port_is_bound(cfg.rtp, SOCK_DGRAM), "rtp port bound");
    bad |= mtx_expect(mtx_port_is_bound(cfg.rtcp, SOCK_DGRAM), "rtcp port bound");
    bad |= mtx_expect(mtx_port_is_bound(cfg.webrtc_ice, SOCK_DGRAM), "webrtc ice port bound");

    for (int i = 0; i < 3; i++) {
        char what[64];
        snprintf(what, sizeof(what), "capture-node port %u unchanged", cn_tcp[i]);
        bad |= mtx_expect(mtx_port_is_bound(cn_tcp[i], SOCK_STREAM) == cn_before[i], what);
    }

    /* Health poll must not declare a live server dead. */
    gui_mediamtx_poll();
    bad |= mtx_expect(gui_mediamtx_is_running(), "still running after poll");

    mtx_sleep((double)seconds);

    int pid = gui_mediamtx_get_status().child_pid;
    gui_mediamtx_stop();
    bad |= mtx_expect(!gui_mediamtx_is_running(), "stopped");
    bad |= mtx_expect(pid <= 0 || kill(pid, 0) != 0 || errno == ESRCH, "no child survives");

    mtx_sleep(0.3);
    bad |= mtx_expect(!mtx_port_is_bound(cfg.rtsp, SOCK_STREAM), "rtsp port released");
    bad |= mtx_expect(!mtx_port_is_bound(cfg.hls, SOCK_STREAM), "hls port released");
    bad |= mtx_expect(!mtx_port_is_bound(cfg.webrtc_http, SOCK_STREAM), "webrtc http port released");

    for (int i = 0; i < 3; i++) {
        char what[64];
        snprintf(what, sizeof(what), "capture-node port %u still unchanged", cn_tcp[i]);
        bad |= mtx_expect(mtx_port_is_bound(cn_tcp[i], SOCK_STREAM) == cn_before[i], what);
    }

    if (bad) {
        fprintf(stderr, "mediamtx test FAILED\n");
        return 1;
    }
    puts("mediamtx test passed");
    return 0;
}

