/* ---- config rendering ---------------------------------------------------- */

gui_mediamtx_config_t gui_mediamtx_default_config(void)
{
    /* mediamtx canonical + 100 across every listener, so the whole set follows
     * one rule. capture-node's scheme is tier x 10000 + its own canonical base,
     * which cannot reach any of these at any tier. */
    gui_mediamtx_config_t cfg = {
        .lan         = false,
        .rtsp        = 8654,
        .rtp         = 8100,
        .rtcp        = 8101,
        .hls         = 8988,
        .webrtc_http = 8989,
        .webrtc_ice  = 8289,
        .metrics     = 10098,
    };
    return cfg;
}

typedef struct {
    char  *out;
    size_t cap;
    size_t len;
    bool   overflow;
} yaml_buf_t;

static void yb_addf(yaml_buf_t *b, const char *fmt, ...)
{
    if (b->overflow) {
        return;
    }
    va_list ap;
    va_start(ap, fmt);
    int n = vsnprintf(b->out + b->len, b->cap - b->len, fmt, ap);
    va_end(ap);
    if (n < 0 || (size_t)n >= b->cap - b->len) {
        b->overflow = true;
        return;
    }
    b->len += (size_t)n;
}

/* Every reader costs bandwidth and CPU on the machine whose RF ingest we go out
 * of our way to protect with nice(+5), so the stream does not get to be an
 * unbounded fan-out. Far above any realistic number of people watching one tape
 * conversion, far below anything that could starve capture. Deliberately not a
 * setting: mediamtx reads 0 as "no limit", so an exposed value is a way for this
 * cap to be switched off by accident. */
#define MTX_MAX_READERS 8

int gui_mediamtx_render_config(const gui_mediamtx_config_t *cfg, char *out, size_t cap)
{
    if (cfg == NULL || out == NULL || cap == 0) {
        return -1;
    }

    /* Loopback pins the host; LAN leaves it off so mediamtx binds every
     * interface. Note there is no auth either way -- see the header. */
    const char *host = cfg->lan ? "" : "127.0.0.1";

    yaml_buf_t b = { out, cap, 0, false };

    yb_addf(&b,
        "# Generated by MISRC GUI - do not edit; rewritten on every launch.\n"
        "#\n"
        "# Ports are mediamtx canonical + 100, chosen so they cannot collide with\n"
        "# capture-node's instances on this host at any tier. Every listener we do\n"
        "# not serve is explicitly off: mediamtx defaults rtmp/srt/moq to yes, and\n"
        "# claiming those ports would take them from a service we do not own.\n"
        "\n");

    yb_addf(&b, "rtsp: yes\n");
    yb_addf(&b, "rtspAddress: %s:%u\n", host, (unsigned)cfg->rtsp);
    yb_addf(&b, "rtpAddress: %s:%u\n", host, (unsigned)cfg->rtp);
    yb_addf(&b, "rtcpAddress: %s:%u\n", host, (unsigned)cfg->rtcp);
    /* Excludes udpMulticast, which mediamtx enables by default and which would
     * bind two more UDP ports we never asked for. */
    yb_addf(&b, "rtspTransports: [udp, tcp]\n");
    /* Keeps RTSPS off, so nothing binds the encrypted RTSP port. */
    yb_addf(&b, "rtspEncryption: \"no\"\n\n");

    yb_addf(&b, "hls: yes\n");
    yb_addf(&b, "hlsAddress: %s:%u\n", host, (unsigned)cfg->hls);
    yb_addf(&b, "hlsVariant: lowLatency\n");
    yb_addf(&b, "hlsAlwaysRemux: no\n\n");

    yb_addf(&b, "webrtc: yes\n");
    yb_addf(&b, "webrtcAddress: %s:%u\n", host, (unsigned)cfg->webrtc_http);
    yb_addf(&b, "webrtcLocalUDPAddress: %s:%u\n", host, (unsigned)cfg->webrtc_ice);
    if (cfg->lan) {
        /* Remote browsers need a reachable ICE candidate. */
        yb_addf(&b, "webrtcIPsFromInterfaces: yes\n\n");
    } else {
        /* Advertising every LAN address for a server nothing off-box can reach
         * only gives browsers candidates that cannot work. */
        yb_addf(&b, "webrtcIPsFromInterfaces: no\n");
        yb_addf(&b, "webrtcAdditionalHosts: [127.0.0.1]\n\n");
    }

    yb_addf(&b,
        "readTimeout: 10s\n"
        "writeTimeout: 10s\n"
        "writeQueueSize: 512\n"
        "\n"
        "rtmp: no\n"
        "srt: no\n"
        "moq: no\n"
        "\n"
        "# These four default to no. So did rtmp/srt/moq -- except those default to\n"
        "# YES, which is the whole reason this file is generated rather than assumed.\n"
        "# A default is not a guarantee, and pprof reachable on a LAN interface\n"
        "# would be a genuine leak, so they are stated.\n"
        "api: no\n"
        "pprof: no\n"
        "playback: no\n"
        "\n");

    /* Metrics is the one admin endpoint we do serve, because it is the only
     * place the real published bitrate exists: ffmpeg's RTSP muxer reports
     * total_size and bitrate as N/A, and the kernel's per-process io counters
     * do not see socket writes. Both were measured before landing here.
     *
     * Bound to 127.0.0.1 unconditionally -- note this does NOT use `host` --
     * so that turning on LAN mode exposes the stream and nothing else. */
    yb_addf(&b, "metrics: yes\n");
    yb_addf(&b, "metricsAddress: 127.0.0.1:%u\n\n", (unsigned)cfg->metrics);

    /* Who may do what.
     *
     * Without this block mediamtx applies its shipped default -- `user: any`
     * with publish, read AND playback on every path. In LAN mode that let any
     * machine on the network publish to misrc-preview and, with
     * overridePublisher on, displace our ffmpeg: the operator monitoring a
     * customer's tape would have been shown someone else's video.
     *
     * Publishing is pinned to loopback in BOTH bind modes. Our publisher always
     * connects to rtsp://127.0.0.1 whatever the bind mode (gui_rtsp_stream.c),
     * so this costs nothing and needs no credential -- which matters, because a
     * credential in ffmpeg's argv would be readable from /proc/<pid>/cmdline by
     * any local user, and would land in its stderr log besides.
     *
     * Reading stays open: passwordless is the documented default, and LAN mode
     * exists precisely so that people can watch. */
    yb_addf(&b,
        "authInternalUsers:\n"
        "  # Our own ffmpeg. Nothing off-box may publish, credential or not.\n"
        "  - user: any\n"
        "    pass:\n"
        /* Quoted deliberately: ::1 is not a valid plain scalar inside a YAML
         * flow sequence, and the unquoted form makes the entire file fail to
         * parse -- mediamtx would refuse to start rather than misbehave, but
         * the stream would simply never come up. mediamtx quotes these in its
         * own shipped config for the same reason. */
        "    ips: [\"127.0.0.1\", \"::1\"]\n"
        "    permissions:\n"
        "      - action: publish\n"
        "        path: misrc-preview\n"
        "  # Viewers, from anywhere the bind mode allows.\n");
    if (cfg->read_password[0]) {
        /* Quoted: the alphabet is alphanumeric and safe unquoted, but a password
         * is exactly the sort of value that should not depend on that staying
         * true. VLC and browsers both prompt for these. */
        yb_addf(&b,
            "  - user: viewer\n"
            "    pass: \"%s\"\n", cfg->read_password);
    } else {
        yb_addf(&b,
            "  - user: any\n"
            "    pass:\n");
    }
    yb_addf(&b,
        "    ips: []\n"
        "    permissions:\n"
        "      - action: read\n"
        "        path: misrc-preview\n"
        "  # Us, reading the bitrate back off the metrics endpoint. Without this\n"
        "  # entry mediamtx answers /metrics with 401 -- which is the auth block\n"
        "  # above doing its job.\n"
        "  - user: any\n"
        "    pass:\n"
        "    ips: [\"127.0.0.1\", \"::1\"]\n"
        "    permissions:\n"
        "      - action: metrics\n"
        "\n");

    /* Deliberately outside capture-node's naming, so the two are never
     * confusable in a viewer's bookmarks. */
    yb_addf(&b,
        "paths:\n"
        "  misrc-preview:\n"
        "    source: publisher\n"
        "    sourceOnDemand: no\n"
        "    # Nothing takes this path out from under the publisher that owns it,\n"
        "    # not even from loopback.\n"
        "    overridePublisher: no\n");
    yb_addf(&b, "    maxReaders: %d\n", MTX_MAX_READERS);

    if (b.overflow) {
        /* Never hand back a truncated config: mediamtx would start on its own
         * defaults, with every listener we meant to disable. */
        out[0] = '\0';
        return -1;
    }
    return (int)b.len;
}


